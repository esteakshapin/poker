// Builds one SQL file for the Supabase SQL Editor: every migration in order, plus your admin email.
//
//   npm run setup-sql      -> writes supabase-setup.local.sql (git-ignored)
//
// The admin email comes from .env (ADMIN_EMAIL=...), which is git-ignored, so it never lands in
// the repository. Everything in supabase/migrations/ is safe to commit as-is.
// The whole file is safe to run again: tables, functions and policies are created only if missing.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';

const env = existsSync('.env') ? Object.fromEntries(readFileSync('.env', 'utf8').split('\n').filter(l => /^[A-Z_]+=/.test(l)).map(l => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1).trim()])) : {};
const email = env.ADMIN_EMAIL;
if (!email || !/^[^@\s']+@[^@\s']+$/.test(email) || email === 'you@example.com') {
  console.error('Set ADMIN_EMAIL in .env first (copy .env.example to .env).'); process.exit(1);
}
const dir = 'supabase/migrations', files = readdirSync(dir).filter(f => f.endsWith('.sql')).sort();
const sql = [
  '-- Generated by `npm run setup-sql`. Paste into Supabase > SQL Editor and click Run.',
  ...files.map(f => `\n-- ===== ${f} =====\n` + readFileSync(`${dir}/${f}`, 'utf8')),
  '\n-- ===== admin =====',
  `insert into public.poker_admins (email) values (lower('${email}')) on conflict do nothing;`, ''
].join('\n');
writeFileSync('supabase-setup.local.sql', sql);
console.log(`Wrote supabase-setup.local.sql (${files.length} migrations + admin email from .env).`);
